void check_fast_65816(const Fast65816Probe& probe, const ::WDC65C816& cpu,
    std::uint64_t cycle_before) {
    const auto& state = cpu.cpu_state;
    const char* difference = nullptr;
    std::uint64_t expected = 0U, actual = 0U;
    const auto compare = [&](const char* name, std::uint64_t library,
                             std::uint64_t fast) {
        if (difference != nullptr || library == fast) return;
        difference = name;
        expected = library;
        actual = fast;
    };
    compare("A", state.regs.a.u16, probe.a);
    compare("X", state.regs.x.u16, probe.x);
    compare("Y", state.regs.y.u16, probe.y);
    compare("D", state.regs.d.u16, probe.d);
    compare("S", state.regs.sp.u16, probe.sp);
    compare("data bank", state.data_segment_base, probe.data_segment_base);
    compare("program bank", state.code_segment_base, probe.code_segment_base);
    compare("ip", state.ip, probe.ip);
    compare("zero", state.zero, probe.zero);
    compare("negative", state.negative, probe.negative);
    compare("interrupts", state.interrupts, probe.interrupts);
    compare("carry", state.carry, probe.carry);
    compare("other flags", state.other_flags, probe.other_flags);
    compare("cycles", state.cycle - cycle_before, probe.cycles);
    compare("open bus", cpu.sys->open_bus, probe.open_bus);
    compare("long A", cpu.mode_long_a, probe.long_a);
    compare("long XY", cpu.mode_long_xy, probe.long_xy);
    compare("emulation", cpu.mode_emulation || cpu.mode_native_6502, false);
    compare("write count", starfox_bus_write_count, probe.write_count);
    for (std::uint32_t index = 0U; index < probe.write_count
            && index < probe.write_address.size(); ++index) {
        compare("write address", starfox_bus_write_address[index],
            probe.write_address[index]);
        compare("write value", starfox_bus_write_value[index],
            probe.write_value[index]);
    }
    if (difference == nullptr) return;
    char text[200]{};
    std::snprintf(text, sizeof(text),
        "compact 65C816 differs at $%06x opcode $%02x: %s is $%llx, library has $%llx",
        static_cast<unsigned>(probe.pc), static_cast<unsigned>(probe.opcode),
        difference, static_cast<unsigned long long>(actual),
        static_cast<unsigned long long>(expected));
    throw std::logic_error{text};
}

