std::size_t run_lean_65816(::WDC65C816& cpu, const Fast65816Tables& tables,
    const Fast65816Call& call) {
    if (call.budget == 0U || !eligible(cpu, tables)) return 0U;
    if (call.service[0] != nullptr && service_pending(call)) return 0U;
    auto* const wram = const_cast<u8*>(tables.collision_ram);
    std::size_t total = 0U;
    bool examined = false;   // the kernel at the current address has had its turn
    for (;;) {
        Fast65816Call part = call;
        part.budget = call.budget - total;
        part.kernels = examined ? Fast65816Call::kernels_after_first : Fast65816Call::kernels_stop;
        kernel_stop = false;
        total += lean_execute(cpu, tables, part);
        if (!kernel_stop || total == call.budget || wram == nullptr) return total;
        // In front of a kernel: let it run alone, then give the interpreter
        // the same instructions from the same state, and compare.
        const u32 address = cpu.program_address();
        unsigned kind = 0U;
        while (kind + 1U < LeanKernels::kinds && tables.kernel_entries[kind] != address) ++kind;
        const CpuImage before = CpuImage::of(cpu);
        const std::vector<u8> memory(wram, wram + 0x20000U);
        part.budget = call.budget - total;
        part.kernels = Fast65816Call::kernels_only;
        const std::size_t claimed = lean_execute(cpu, tables, part);
        examined = true;
        if (claimed == 0U) { ++kernel_stats.declined[kind]; continue; }
        const CpuImage native = CpuImage::of(cpu);
        const std::vector<u8> native_memory(wram, wram + 0x20000U);
        before.restore(cpu);
        std::memcpy(wram, memory.data(), memory.size());
        part.budget = claimed;
        part.kernels = Fast65816Call::kernels_off;
        const std::size_t ran = lean_execute(cpu, tables, part);
        const CpuImage reference = CpuImage::of(cpu);
        if (ran != claimed) kernel_differs(address, "instructions", ran, claimed);
#define STARFOX_KERNEL_FIELD(name) \
        if (reference.name != native.name) kernel_differs(address, #name, reference.name, native.name)
        STARFOX_KERNEL_FIELD(ip); STARFOX_KERNEL_FIELD(program_bank);
        STARFOX_KERNEL_FIELD(a); STARFOX_KERNEL_FIELD(x); STARFOX_KERNEL_FIELD(y);
        STARFOX_KERNEL_FIELD(d); STARFOX_KERNEL_FIELD(sp); STARFOX_KERNEL_FIELD(data_bank);
        STARFOX_KERNEL_FIELD(zero); STARFOX_KERNEL_FIELD(negative); STARFOX_KERNEL_FIELD(interrupts);
        STARFOX_KERNEL_FIELD(carry); STARFOX_KERNEL_FIELD(other); STARFOX_KERNEL_FIELD(cycle);
        STARFOX_KERNEL_FIELD(instructions); STARFOX_KERNEL_FIELD(long_a); STARFOX_KERNEL_FIELD(long_xy);
        STARFOX_KERNEL_FIELD(open_bus);
#undef STARFOX_KERNEL_FIELD
        for (u32 at = 0U; at < 0x20000U; ++at)
            if (wram[at] != native_memory[at]) {
                char what[40]{};
                std::snprintf(what, sizeof(what), "byte $7e%04x", static_cast<unsigned>(at));
                kernel_differs(address, what, wram[at], native_memory[at]);
            }
        ++kernel_stats.compared[kind];
        kernel_stats.instructions[kind] += claimed;
        total += claimed;
        if (total == call.budget) return total;
    }
}
