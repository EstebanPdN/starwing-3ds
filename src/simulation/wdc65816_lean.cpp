// Everything the loop loads from and stores to the library's CPU.
struct CpuImage {
    std::uint16_t a, x, y, d, sp;
    u32 data_bank, program_bank, ip, zero, negative, interrupts, carry, other;
    std::uint64_t cycle, instructions;
    bool long_a, long_xy;
    u8 open_bus;

    static CpuImage of(const ::WDC65C816& cpu) {
        const auto& s = cpu.cpu_state;
        return {s.regs.a.u16, s.regs.x.u16, s.regs.y.u16, s.regs.d.u16, s.regs.sp.u16,
            s.data_segment_base, s.code_segment_base, s.ip, s.zero, s.negative, s.interrupts,
            s.carry, s.other_flags, s.cycle, cpu.num_emulated_instructions,
            cpu.mode_long_a, cpu.mode_long_xy, cpu.sys->open_bus};
    }
    void restore(::WDC65C816& cpu) const {
        auto& s = cpu.cpu_state;
        s.regs.a.u16 = a; s.regs.x.u16 = x; s.regs.y.u16 = y; s.regs.d.u16 = d; s.regs.sp.u16 = sp;
        s.data_segment_base = data_bank; s.code_segment_base = program_bank; s.ip = ip;
        s.zero = zero; s.negative = negative; s.interrupts = interrupts; s.carry = carry;
        s.other_flags = other; s.cycle = cycle;
        cpu.num_emulated_instructions = instructions;
        if (cpu.mode_long_a != long_a || cpu.mode_long_xy != long_xy) {
            cpu.mode_long_a = long_a; cpu.mode_long_xy = long_xy;
            cpu.OnUpdateMode();
        }
        cpu.sys->open_bus = open_bus;
    }
};

[[noreturn]] void kernel_differs(u32 address, const char* what, std::uint64_t interpreter,
    std::uint64_t kernel) {
    char text[200]{};
    std::snprintf(text, sizeof(text),
        "kernel at $%06x differs from the interpreter: %s is $%llx, the interpreter has $%llx",
        static_cast<unsigned>(address), what, static_cast<unsigned long long>(kernel),
        static_cast<unsigned long long>(interpreter));
    throw std::logic_error(text);
}
