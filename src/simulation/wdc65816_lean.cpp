void Fast65816Tables::build(const SystemBus& bus, std::uint32_t rom_banks,
    std::span<const Range> stop_ranges) {
    usable = false;
    if (bus.memory.page_shift != page_bits || bus.mem_mask != 0xffffffU
        || !bus.open_bus_is_data) return;
    stop_pages.clear();
    for (std::size_t page = 0U; page < page_count; ++page) {
        const Page& source = bus.memory.pages[page];
        // The loop adds one cycle per access, as every page here is mapped.
        if (source.cycles_per_access != 1U) return;
        // (io_mask & address) == io_eq can hold nowhere in the page.
        const bool plain = source.ptr != nullptr && source.io_mask == 0U
            && source.io_eq != 0U;
        read[page] = plain ? source.ptr : nullptr;
        write[page] = plain && (source.flags & Page::kReadOnly) == 0U
            ? source.ptr : nullptr;
        const auto bank = static_cast<std::uint32_t>(page >> 4U);
        const bool outside_rom = (page & 8U) != 0U && (bank & 0x7fU) >= rom_banks;
        // The caller reports execution in a ROM half beyond the image.
        guarded[page] = !plain || outside_rom ? never_runs : 0U;
    }
    const auto mark = [this](std::uint32_t address, std::uint8_t stop) {
        auto& guard = guarded[address >> page_bits];
        if (guard == never_runs) return true;
        if (guard == 0U) {
            if (stop_pages.size() == never_runs - 1U) return false;
            stop_pages.emplace_back();
            guard = static_cast<std::uint8_t>(stop_pages.size());
        }
        stop_pages[guard - 1U][address & 0xfffU] |= stop;
        return true;
    };
    // The first row serves every bank that holds no other stop: near and
    // long calls return to $01f0 of the callee's bank or of $7e.
    stop_pages.emplace_back();
    stop_pages.front()[0x1f0U] = stop_return;
    for (std::size_t bank = 0U; bank < 256U; ++bank)
        if (guarded[bank << 4U] == 0U) guarded[bank << 4U] = 1U;
    for (const auto& range : stop_ranges) {
        if (range.first == 0U) continue;
        if (range.last < range.first || range.last > 0xffffffU) return;
        for (auto address = range.first; address <= range.last; ++address) {
            if ((address & 0xf000U) == 0U && guarded[address >> page_bits] == 1U) {
                // This bank's first page needs a row of its own.
                stop_pages.push_back(stop_pages.front());
                if (stop_pages.size() >= never_runs) return;
                guarded[address >> page_bits] =
                    static_cast<std::uint8_t>(stop_pages.size());
            }
            if (!mark(address, range.stop)) return;
        }
    }
    for (std::size_t page = 0U; page < page_count; ++page) {
        const auto own = static_cast<std::uintptr_t>(page) << page_bits;
        read_biased[page] = read[page] != nullptr
            ? reinterpret_cast<std::uintptr_t>(read[page]) - own : 0U;
        write_biased[page] = write[page] != nullptr
            ? reinterpret_cast<std::uintptr_t>(write[page]) - own : 0U;
    }
    stop_marks.assign(stop_pages.size(), {});
    for (std::size_t row = 0U; row < stop_pages.size(); ++row)
        for (std::uint32_t offset = 0U; offset < stop_pages[row].size(); ++offset)
            if (stop_pages[row][offset] != 0U)
                stop_marks[row].push_back(static_cast<std::uint16_t>(offset));
    watch = {};
    collision_ram = read[0x7e0];
    for (unsigned i = 0; i < 32 && collision_ram; ++i)
        if (read[0x7e0 + i] != collision_ram + i * 4096U || write[0x7e0 + i] != collision_ram + i * 4096U)
            collision_ram = nullptr;
    if (collision_ram && (read[0] != collision_ram || write[0] != collision_ram
        || read[1] != collision_ram + 4096U || write[1] != collision_ram + 4096U)) collision_ram = nullptr;
    if (collision_ram != nullptr) {
        watch.base = const_cast<std::uint8_t*>(collision_ram) + LeanWatch::first;
        watch.size = LeanWatch::last - LeanWatch::first;
    }
    usable = true;
}

